async (page) => {
  const results = [];
  const check = (value, name) => { if (!value) throw new Error(name); results.push(name); };
  const fit = async (label) => {
    const m = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth, header: document.querySelector('header').getBoundingClientRect().top }));
    check(m.scroll <= m.width, label + ': no horizontal overflow');
    check(m.header >= -1 && m.header < 2, label + ': sticky header at viewport top');
  };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://127.0.0.1:3100');
  await page.evaluate(() => document.fonts.ready);
  await fit('desktop');
  check(await page.locator('.brand img').first().evaluate(img => img.complete && img.naturalWidth > 0), 'logo loads');
  await page.getByRole('link', {name: 'Pilih game', exact: true}).click();
  check(await page.getByRole('status').innerText() === '3 layanan dalam Top up game', 'hero game link filters catalog');
  await page.getByRole('link', {name: 'Lihat jasa tugas', exact: true}).click();
  check((await page.getByRole('status').innerText()).startsWith('1 layanan'), 'task link filters catalog');
  for (const [name, count] of [['Semua',8],['Top up game',3],['Aplikasi premium',1],['Pulsa & tagihan',2],['Media sosial',1],['Format tugas',1]]) {
    await page.getByRole('button',{name,exact:true}).click();
    check((await page.getByRole('status').innerText()).startsWith(count + ' layanan'), 'filter ' + name);
  }
  await page.getByRole('button', {name:'Semua',exact:true}).click();
  const search = page.getByRole('searchbox', {name:'Cari layanan'});
  await search.fill('roblox');
  check(await page.getByRole('button',{name:'Roblox Lihat layanan'}).count() === 1, 'search finds Roblox');
  await page.getByRole('button',{name:'Hapus pencarian'}).hover();
  await page.getByRole('tooltip').waitFor();
  check(await page.getByRole('tooltip').isVisible(), 'clear tooltip shows');
  await page.getByRole('button',{name:'Hapus pencarian'}).click();
  check(await search.inputValue() === '', 'clear search');
  await search.fill('  does-not-exist  ');
  check(await page.getByRole('heading',{name:'Belum ketemu.'}).isVisible(), 'no-match empty state');
  await page.getByRole('button',{name:'Lihat semua layanan',exact:true}).click();
  await page.getByRole('button',{name:'Aplikasi premium',exact:true}).click();
  await search.fill('Mobile Legends');
  check(await page.getByRole('heading',{name:'Belum ketemu.'}).isVisible(), 'combined search/filter empty state');
  await page.getByRole('button',{name:'Lihat semua layanan',exact:true}).click();
  await search.fill('   ');
  check((await page.getByRole('status').innerText()).startsWith('8 layanan'), 'whitespace query');
  await page.getByRole('button',{name:'Hapus pencarian'}).click();
  const service = page.getByRole('button',{name:'Mobile Legends Lihat layanan'});
  await service.click();
  await page.getByRole('dialog').waitFor();
  check(await page.getByRole('dialog').getByRole('heading',{name:'Mobile Legends'}).isVisible(), 'service dialog opens');
  await page.screenshot({path:'output/playwright/redesign-dialog.png',scale:'css'});
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({state:'hidden'});
  check(await page.getByRole('dialog').count() === 0, 'dialog Escape closes');
  check(await service.evaluate(el => el === document.activeElement), 'dialog returns focus');
  await service.click();
  await page.getByRole('button',{name:'Tutup detail'}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  check(await page.getByRole('dialog').count() === 0, 'dialog close button');
  await service.click();
  await page.getByRole('button',{name:'Kembali ke katalog'}).click();
  await service.click();
  await page.mouse.click(10,500);
  await page.getByRole('dialog').waitFor({state:'hidden'});
  check(await page.getByRole('dialog').count() === 0, 'dialog outside click');
  await page.getByRole('link',{name:'Bantuan',exact:true}).click();
  const faq = page.getByRole('button',{name:'Sudah bisa transaksi di website ini?'});
  await faq.click();
  check(await faq.getAttribute('aria-expanded') === 'true', 'FAQ opens');
  await page.screenshot({path:'output/playwright/redesign-faq.png',scale:'css'});
  const faq2 = page.getByRole('button',{name:'Apa saja layanan Anres Store?'});
  await faq2.click();
  check(await faq.getAttribute('aria-expanded') === 'false', 'FAQ switches');
  await faq2.press('Enter');
  check(await faq2.getAttribute('aria-expanded') === 'false', 'FAQ closes by keyboard');
  await page.getByRole('button',{name:'Di mana harga dan kontak bantuan?'}).click();
  await page.getByRole('button',{name:'Di mana harga dan kontak bantuan?'}).click();
  await fit('desktop after scroll');
  await page.getByRole('link',{name:'Cara order',exact:true}).click();
  await page.screenshot({path:'output/playwright/redesign-order.png',scale:'css'});
  await page.getByRole('link',{name:'Anres Store kembali ke atas'}).click();
  await page.getByRole('link',{name:'Cari layanan',exact:true}).click();
  check(await search.evaluate(el => el === document.activeElement), 'nav search focuses input');
  await page.getByRole('link',{name:'Anres Store beranda'}).click();
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://127.0.0.1:3100');
  await fit('mobile');
  await page.getByRole('button',{name:'Buka menu'}).click();
  check(await page.getByRole('navigation',{name:'Navigasi mobile'}).isVisible(), 'mobile menu opens');
  await page.screenshot({path:'output/playwright/redesign-mobile-menu.png',scale:'css'});
  await page.getByRole('button',{name:'Tutup menu'}).click();
  check(await page.getByRole('navigation',{name:'Navigasi mobile'}).count() === 0, 'mobile menu closes');
  await page.getByRole('button',{name:'Buka menu'}).click();
  await page.keyboard.press('Escape');
  check(await page.getByRole('navigation',{name:'Navigasi mobile'}).count() === 0, 'mobile menu Escape');
  await page.getByRole('button',{name:'Buka menu'}).click();
  await page.getByRole('navigation',{name:'Navigasi mobile'}).getByRole('link',{name:'Katalog'}).click();
  check(await page.getByRole('navigation',{name:'Navigasi mobile'}).count() === 0, 'mobile menu link closes menu');
  await page.getByRole('button',{name:'Format tugas',exact:true}).click();
  await page.getByRole('button',{name:'Rapikan tugas Lihat layanan'}).click();
  await page.screenshot({path:'output/playwright/redesign-mobile-dialog.png',scale:'css'});
  await page.getByRole('button',{name:'Kembali ke katalog'}).click();
  await page.getByRole('button',{name:'Semua',exact:true}).click();
  await page.screenshot({path:'output/playwright/redesign-mobile-catalog.png',scale:'css'});
  await fit('mobile catalog');
  await page.setViewportSize({width:360,height:800});
  await page.goto('http://127.0.0.1:3100');
  await fit('minimum 360');
  await page.screenshot({path:'output/playwright/redesign-mobile-360.png',scale:'css'});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.getByRole('link',{name:'Pilih game',exact:true}).click();
  check((await page.getByRole('status').innerText()).startsWith('3 layanan'), 'reduced motion filtering works');
  await page.emulateMedia({reducedMotion:'no-preference'});
  console.log(JSON.stringify({passed:results.length,checks:results},null,2));
}
